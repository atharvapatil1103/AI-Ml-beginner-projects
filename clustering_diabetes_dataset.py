import pandas as pd
import matplotlib.pyplot as plt
import numpy as np

df_pregnancy=pd.read_csv("/content/diabetes.csv")

display(df_pregnancy)

df_pregnancy=df_pregnancy.drop(["Outcome"],axis=1,errors="ignore")
df_pregnancy

from sklearn.preprocessing import StandardScaler # formula => xi-xmean/xstd deviation
scaler=StandardScaler()
scaled_value=scaler.fit_transform(df_pregnancy)

scaled_value

from sklearn.cluster import KMeans

wccs=[]
for k in range(1,11):
  kmeans=KMeans(n_clusters=k,init="k-means++",random_state=42)
  kmeans.fit(scaled_value)
  wccs.append(kmeans.inertia_)#inertia is wccs in sklearn

plt.plot(range(1,11),wccs,marker='x')
plt.title("The Elbow Method")
plt.xlabel("Number of Clusters")
plt.ylabel("WCSS")
plt.show()

km=KMeans(n_clusters=6)
km.fit(scaled_value)
y=km.predict(scaled_value)
df_pregnancy["label"]=y
